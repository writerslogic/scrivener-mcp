// Regenerates vectors.json from a fixed, public, test-only key. Never use this key for real licenses.
import { writeFileSync } from 'node:fs';
import { privateKeyFromSeed, rawPublicKey, seal } from './issuer.mjs';

const seed = Buffer.from(Array.from({ length: 32 }, (_, i) => i + 1));
const key = privateKeyFromSeed(seed);
const kid = 'test';
const device = 'device-test-1';
const license = seal('license', { v: 1, kid, id: 'lic_test_1', email: 'reader@example.com', iat: 1_700_000_000, seats: 2, product: 'draftbridge' }, key);
const vectors = {
	note: 'Test-only key. Generated by make-vectors.mjs; Swift and Node must both verify these.',
	kid,
	publicKey: rawPublicKey(key),
	device,
	license,
	receipt: seal('receipt', { v: 1, kid, id: 'lic_test_1', dev: device, iat: 1_700_000_100 }, key),
	revocations: seal('revocations', { v: 1, kid, iat: 1_700_000_200, ids: ['lic_other'] }, key),
	revocationsWithLicense: seal('revocations', { v: 1, kid, iat: 1_700_000_300, ids: ['lic_test_1'] }, key),
};
writeFileSync(new URL('./vectors.json', import.meta.url), `${JSON.stringify(vectors, null, '\t')}\n`);
console.log('wrote vectors.json');
