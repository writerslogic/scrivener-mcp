import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import { format } from 'prettier';

const { values: args } = parseArgs({
	options: { archive: { type: 'string' }, check: { type: 'boolean' } },
});
assert(
	args.archive,
	'Supply --archive downloaded from https://wordnetcode.princeton.edu/wn3.1.dict.tar.gz'
);
const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const archive = await readFile(args.archive);
assert.equal(
	sha256(archive),
	'3f7d8be8ef6ecc7167d39b10d66954ec734280b5bdcd57f7d9eafe429d11c22a',
	'Unexpected WordNet archive'
);
const data = execFileSync('tar', ['-xOf', args.archive, 'dict/data.noun'], {
	encoding: 'utf8',
	maxBuffer: 32 * 1024 * 1024,
});
const synsets = new Map(),
	senses = new Map();
const license = [];
for (const line of data.split('\n')) {
	if (line.startsWith(' ')) {
		license.push(line.replace(/^\s+\d+\s?/, '').trimEnd());
		continue;
	}
	if (!line) continue;
	const fields = line.split('|')[0].trim().split(/\s+/);
	const count = parseInt(fields[3], 16);
	const words = Array.from({ length: count }, (_, i) => fields[4 + i * 2]);
	let index = 4 + count * 2;
	const pointers = Number(fields[index++]);
	const parents = [];
	for (let i = 0; i < pointers; i++, index += 4)
		if (['@', '@i'].includes(fields[index]) && fields[index + 2] === 'n')
			parents.push(fields[index + 1]);
	assert.equal(index, fields.length, 'Unexpected noun record');
	synsets.set(fields[0], { words, category: Number(fields[1]), parents });
	for (const word of words)
		if (/^[a-z]+(?:-[a-z]+)*$/.test(word)) {
			if (!senses.has(word)) senses.set(word, []);
			senses.get(word).push(fields[0]);
		}
}
// Exclude living entities, agents, collectives, and depictions of bodily/person forms.
const excludedRoots = new Map([
	['00004258', 'living_thing'],
	['00007347', 'causal_agent'],
	['00031563', 'group'],
	['02764397', 'automaton'],
	['03340545', 'figure'],
	['03993437', 'portrait'],
	['04164381', 'sculpture'],
	['07217051', 'portrait'],
]);
for (const [id, word] of excludedRoots)
	assert(synsets.get(id)?.words.includes(word), 'WordNet concept drift');
const unsafe = new Map();
function hasExcludedAncestor(id, visiting = new Set()) {
	if (unsafe.has(id)) return unsafe.get(id);
	assert(!visiting.has(id), 'Cyclic WordNet ancestry');
	const synset = synsets.get(id);
	assert(synset, 'Missing WordNet parent');
	visiting.add(id);
	const result =
		excludedRoots.has(id) ||
		synset.parents.some((parent) => hasExcludedAncestor(parent, visiting));
	visiting.delete(id);
	unsafe.set(id, result);
	return result;
}
const accepted = [],
	rejected = [],
	materials = [];
for (const [word, ids] of [...senses].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
	if (ids.some((id) => synsets.get(id).category === 27)) materials.push(word);
	const nonpersonal = ids.every(
		(id) => ![3, 5, 14, 18].includes(synsets.get(id).category) && !hasExcludedAncestor(id)
	);
	(nonpersonal ? accepted : rejected).push(word);
}
const generated = await format(
	`/*
Generated by scripts/generate-continuity-nouns.mjs from Princeton WordNet 3.1.
Source: https://wordnetcode.princeton.edu/wn3.1.dict.tar.gz
Archive SHA-256: ${sha256(archive)}
Noun data SHA-256: ${sha256(data)}
All noun senses are checked; unknown nouns are not classified as nonpersonal.

${license.join('\n')}
*/
const nonpersonal = new Set(${JSON.stringify(accepted.join(' '))}.split(' '));
const ambiguous = new Set(${JSON.stringify(rejected.join(' '))}.split(' '));
const materials = new Set(${JSON.stringify(materials.join(' '))}.split(' '));
export function isMaterialNoun(word: string): boolean { return materials.has(word); }
export function classifyNoun(word: string): 'nonpersonal' | 'ambiguous' | 'unknown' {
  if (nonpersonal.has(word)) return 'nonpersonal';
  return ambiguous.has(word) ? 'ambiguous' : 'unknown';
}
`,
	{
		parser: 'typescript',
		useTabs: true,
		singleQuote: true,
		trailingComma: 'es5',
		printWidth: 100,
	}
);
const target = new URL('../src/services/editorial/continuity-nouns.ts', import.meta.url);
if (args.check)
	assert.equal(await readFile(target, 'utf8'), generated, 'Generated noun classification drift');
else await writeFile(target, generated);
console.log(
	JSON.stringify({
		nonpersonal: accepted.length,
		ambiguous: rejected.length,
		bytes: Buffer.byteLength(generated),
	})
);
