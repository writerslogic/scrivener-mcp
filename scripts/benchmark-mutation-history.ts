const { values } = parseArgs({
	options: {
		output: { type: 'string' },
		edits: { type: 'string', default: '10000' },
		documents: { type: 'string', default: '32' },
		characters: { type: 'string', default: '16000' },
	},
	strict: true,
});
function bounded(
	value: string | undefined,
	name: string,
	minimum: number,
	maximum: number
): number {
	const count = Number(value);
	if (!Number.isSafeInteger(count) || count < minimum || count > maximum)
		throw new Error(`${name} must be an integer from ${minimum} through ${maximum}`);
	return count;
}
const edits = bounded(values.edits, 'edits', 1, 10000);
const documents = bounded(values.documents, 'documents', 1, 100);
const characters = bounded(values.characters, 'characters', 1024, 32768);
if (!values.output) throw new Error('--output is required');
const output = resolve(values.output);
await mkdir(dirname(output), { recursive: true });
await writeFile(output, '{"status":"initializing"}\n', { flag: 'wx' });
const hash = (value: string | Buffer) => createHash('sha256').update(value).digest('hex');
const sourceFiles = execFileSync('rg', ['--files', 'src'], { encoding: 'utf8' })
	.trim()
	.split('\n')
	.sort();
const sourceManifest = await Promise.all(
	sourceFiles.map(async (file) => ({ file, sha256: hash(await readFile(file)) }))
);
const sampleParagraph =
	'Mara carried the brass compass across the harbor. The keeper recorded each arrival in a blue ledger, then returned the key to its drawer. At dusk they compared the map with the marked stones and agreed to wait for the morning tide.\n\n';
const scenes = Array.from({ length: documents }, (_, index) =>
	(
		`Scene ${index + 1}.\n` +
		sampleParagraph.repeat(Math.ceil(characters / sampleParagraph.length))
	).slice(0, characters)
);
const ids = scenes.map(
	(_, index) => `10000000-0000-4000-8000-${String(index + 1).padStart(12, '0')}`
);
const samples: Array<{
	edit: number;
	documentId: string;
	elapsedMs: number;
	beforeBytes: number;
	afterBytes: number;
}> = [];
const checkpoints: Array<Record<string, unknown>> = [];
const report: Record<string, unknown> = {
	status: 'running',
	processObserverDeadlineMs: PROCESS_OBSERVER_TIMEOUT_MS,
	revision: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(),
	sourceTreeSha256: hash(JSON.stringify(sourceManifest)),
	sourceManifest,
	scriptSha256: hash(await readFile(new URL(import.meta.url))),
	resourceHelperSha256: hash(
		await readFile(new URL('./lib/benchmark-process-tree.ts', import.meta.url))
	),
	environment: {
		node: process.version,
		v8: process.versions.v8,
		platform: process.platform,
		arch: process.arch,
		osRelease: release(),
		cpu: cpus()[0]?.model,
		logicalCpus: cpus().length,
		totalMemoryBytes: totalmem(),
		loadAverageBefore: loadavg(),
	},
	workload: {
		edits,
		documents,
		charactersPerScene: characters,
		corpusSha256: hash(JSON.stringify(scenes)),
		origin: 'Original deterministic prose generated by this script',
		snapshots: 'Native snapshot per saved-document edit',
		samplingIntervalMs: 5,
	},
	limitations: [
		'One deterministic storage-growth trial; no p95 or general latency claim.',
		'Direct MutationCoordinator calls include journal, native snapshots and checksum publication; no MCP, provider, model or GUI work.',
		'Parent RSS includes native SQLite but excludes loader helpers. Process/descendant RSS and cumulative CPU are observed separately before/after and at1000-edit checkpoints, excluding the ps observer. The mutation logic starts no workload subprocess; loader-helper peaks between checkpoints remain unmeasured.',
		'Sampled RSS and event-loop delay may miss peaks; checkpoints and reopen checks are timed separately.',
		'Resource isolation is operator-enforced, not automatic: pause competing mission builds/tests before timing. Unrelated host activity is uncontrolled.',
	],
	samples,
	checkpoints,
};
async function saveReport() {
	const temporary = output + '.partial';
	await writeFile(temporary, JSON.stringify(report, null, 2) + '\n');
	await rename(temporary, output);
}
async function diskUsage(
	directory: string
): Promise<{ logicalBytes: number; allocatedBytes: number; files: number }> {
	let logicalBytes = 0,
		allocatedBytes = 0,
		files = 0;
	for (const entry of await readdir(directory, { withFileTypes: true })) {
		const file = join(directory, entry.name);
		if (entry.isDirectory()) {
			const nested = await diskUsage(file);
			logicalBytes += nested.logicalBytes;
			allocatedBytes += nested.allocatedBytes;
			files += nested.files;
		} else {
			const info = await stat(file);
			logicalBytes += info.size;
			allocatedBytes += info.blocks * 512;
			files++;
		}
	}
	return { logicalBytes, allocatedBytes, files };
}
const root = await mkdtemp(join(tmpdir(), 'scrivener-mutation-scale-'));
const database = join(root, '.scrivener-mcp', 'editorial.sqlite');
const rtf = new RTFHandler();
let store: PersistentStore | undefined;
let coordinator: MutationCoordinator | undefined;
let timer: ReturnType<typeof setInterval> | undefined;
const initialRaw = scenes.map((scene) => rtf.convertToRTF(scene));
const currentRaw = [...initialRaw];
const retentionLimits = mutationRetentionLimits();
report.retentionLimits = retentionLimits;
interface RetentionUsage {
	bytes: number;
	records: number;
	entries: number;
}
try {
	for (let i = 0; i < documents; i++) {
		const file = join(root, 'Files', 'Data', ids[i], 'content.rtf');
		await mkdir(dirname(file), { recursive: true });
		await writeFile(file, initialRaw[i]);
	}
	store = new PersistentStore(database);
	coordinator = new MutationCoordinator(root, store);
	await coordinator.recover();
	checkpoints.push({
		edits: 0,
		journal: store.usage('mutations'),
		disk: await diskUsage(root),
		processTree: await processTree(),
	});
	const memoryBefore = process.memoryUsage();
	const cpuBefore = process.cpuUsage();
	let rssPeakBytes = memoryBefore.rss,
		eventLoopLagMs = 0,
		ticks = 0,
		lastTick = performance.now();
	timer = setInterval(() => {
		const now = performance.now();
		eventLoopLagMs = Math.max(eventLoopLagMs, now - lastTick - 5);
		lastTick = now;
		ticks++;
		rssPeakBytes = Math.max(rssPeakBytes, process.memoryUsage.rss());
	}, 5);
	const start = performance.now();
	for (let i = 0; i < edits; i++) {
		const index = i % documents;
		const after = rtf.convertToRTF(
			`${scenes[index]}\nRevision ${String(i + 1).padStart(5, '0')}.`
		);
		const started = performance.now();
		const result: MutationRecord = await coordinator.commit(ids[index], after, {
			expectedRevision: documentRevision(currentRaw[index]),
			operationId: `scale-${String(i + 1).padStart(6, '0')}`,
		});
		assert.equal(result.state, 'committed');
		assert.equal(result.beforeRaw, currentRaw[index]);
		assert.equal(result.afterRaw, after);
		samples.push({
			edit: i + 1,
			documentId: ids[index],
			elapsedMs: performance.now() - started,
			beforeBytes: Buffer.byteLength(currentRaw[index]),
			afterBytes: Buffer.byteLength(after),
		});
		currentRaw[index] = after;
		if ((i + 1) % 1000 === 0 || i + 1 === edits) {
			const checkpointStarted = performance.now();
			checkpoints.push({
				edits: i + 1,
				journal: store.usage('mutations'),
				reservation: store.get<RetentionUsage>('mutation-meta', 'retention-usage-v1'),
				disk: await diskUsage(root),
				memory: process.memoryUsage(),
				processTree: await processTree(),
			});
			report.progress = {
				completed: i + 1,
				elapsedMs: performance.now() - start,
				checkpointMs: performance.now() - checkpointStarted,
			};
			await saveReport();
			process.stdout.write(JSON.stringify(report.progress) + '\n');
		}
	}
	clearInterval(timer);
	timer = undefined;
	report.editLoop = {
		elapsedMs: performance.now() - start,
		cpu: process.cpuUsage(cpuBefore),
		memoryBefore,
		memoryAfter: process.memoryUsage(),
		rssPeakBytes,
		eventLoopLagMs,
		ticks,
		parentLifetimeHighWaterBytes: process.resourceUsage().maxRSS * 1024,
	};
	await coordinator.close();
	store.close();
	const reopenStart = performance.now();
	store = new PersistentStore(database);
	coordinator = new MutationCoordinator(root, store);
	await coordinator.recover();
	for (let i = 0; i < documents; i++)
		assert.equal((await coordinator.readRaw(ids[i])).raw, currentRaw[i]);
	assert.equal(coordinator.get('scale-000001')?.beforeRaw, initialRaw[0]);
	const lastIndex = (edits - 1) % documents;
	const prior = coordinator.get(`scale-${String(edits).padStart(6, '0')}`)!;
	const retried = await coordinator.commit(ids[lastIndex], prior.afterRaw, {
		expectedRevision: prior.beforeRevision,
		operationId: prior.id,
	});
	assert.equal(retried.id, prior.id);
	assert.equal(store.usage('mutations').count, edits);
	report.reopen = {
		elapsedMs: performance.now() - reopenStart,
		allSavedBytesMatch: true,
		firstReceiptRetained: true,
		retryDidNotDuplicateReceipt: true,
	};
	const reservationBefore = store.get<RetentionUsage>('mutation-meta', 'retention-usage-v1')!;
	assert.equal(reservationBefore.records, edits * 2);
	assert.equal(reservationBefore.entries, edits);
	assert(reservationBefore.bytes <= retentionLimits.maxBytes);
	if (edits === 10000) {
		assert.deepEqual(retentionLimits, { maxRecords: 20000, maxBytes: 1024 * 1024 * 1024 });
		await assert.rejects(
			coordinator.commit(ids[lastIndex], prior.beforeRaw, {
				operationId: 'scale-over-budget',
				expectedRevision: prior.afterRevision,
			}),
			/Mutation history capacity reached/
		);
		assert.equal(store.usage('mutations').count, edits);
		assert.equal((await coordinator.readRaw(ids[lastIndex])).raw, prior.afterRaw);
	}
	const inverse = {
		operationId: 'scale-final-inverse',
		undoes: prior.id,
		expectedRevision: prior.afterRevision,
		snapshotTitle: 'Before undo of reviewed edit',
	};
	await coordinator.commit(ids[lastIndex], prior.beforeRaw, inverse);
	await coordinator.commit(ids[lastIndex], prior.beforeRaw, inverse);
	assert.equal((await coordinator.readRaw(ids[lastIndex])).raw, prior.beforeRaw);
	assert.equal(store.usage('mutations').count, edits + 1);
	const reservationAfter = store.get<RetentionUsage>('mutation-meta', 'retention-usage-v1')!;
	assert.deepEqual(reservationAfter, { ...reservationBefore, entries: edits + 1 });
	report.inverseUndo = {
		restoredExactBeforeImage: true,
		retryDidNotDuplicateReceipt: true,
		quotaRefusalVerified: edits === 10000,
		reservationBefore,
		reservationAfter,
		finalJournal: store.usage('mutations'),
	};
	await coordinator.close();
	coordinator = undefined;
	store.close();
	store = undefined;
	report.closedDisk = await diskUsage(root);
	report.processTreeAfterClose = await processTree();
	report.status = 'complete';
	report.loadAverageAfter = loadavg();
} catch (error) {
	report.status = 'failed';
	report.failure =
		error instanceof Error
			? { name: error.name, message: error.message }
			: { name: 'Error', message: String(error) };
	process.exitCode = 1;
} finally {
	if (timer) clearInterval(timer);
	await coordinator?.close();
	store?.close();
	await saveReport();
	await rm(root, { recursive: true, force: true });
}
